"""The desk's research lead, ported from frontend/src/lib/optionResearchLead.ts.

A deterministic quote-quality order within the API's bounded shortlist (spread, then OI, anchor
distance, expiry, identity), not a return forecast. Ported with EMPTY search preferences; the
TypeScript also applies the user's preference blocker, which is not reproduced here. Shared golden
cases (tests/fixtures/option_research_lead_golden.json, generated by
frontend/src/lib/optionResearchLead.golden.test.ts) pin the port to the reference. Used by the
candidate outcome study (Part A) and the daily desk record (Part B).
"""
from __future__ import annotations

import math
from datetime import date

_MAX_SPREAD_PCT = 20.0          # the desk's existing research spread screen, not an optimised rule
_UNSET = object()


def _dte(expiry, today: date):
    try:
        return (date.fromisoformat(str(expiry)[:10]) - today).days
    except (TypeError, ValueError):
        return None


def _finite(x) -> bool:
    return isinstance(x, (int, float)) and not isinstance(x, bool) and math.isfinite(x)


def lead_valid(key: str, strategy, today: date, holding_days=_UNSET) -> bool:
    """The TypeScript `valid()` predicate, with empty preferences."""
    if not strategy or len(strategy.get("legs") or []) != 1:
        return False
    leg = strategy["legs"][0]
    expected = "call" if key.endswith("call") else "put"
    action = "buy" if key in ("long_call", "protective_put") else "sell"
    dte = _dte(leg.get("expiry"), today)
    price, net = leg.get("price_per_share"), strategy.get("net_per_contract")
    spread, oi, maxp = leg.get("spread_pct"), leg.get("oi"), strategy.get("max_profit_per_contract", _UNSET)
    if not (leg.get("right") == expected and leg.get("action") == action and leg.get("option_symbol")):
        return False
    if not (_finite(leg.get("strike")) and leg["strike"] > 0 and leg.get("price_source") == "quote_mid"):
        return False
    if not (_finite(price) and price > 0 and _finite(net) and net > 0 and abs(net - price * 100) <= .02):
        return False
    if not (_finite(spread) and 0 <= spread <= _MAX_SPREAD_PCT):
        return False
    if not (_finite(oi) and float(oi).is_integer() and oi > 0 and dte is not None and dte > 0):
        return False
    if holding_days is not _UNSET:
        if not (isinstance(holding_days, int) and not isinstance(holding_days, bool)
                and holding_days >= 1 and dte >= holding_days + 2):
            return False
    if maxp is _UNSET:
        return False
    return maxp is None or (_finite(maxp) and maxp > 0)


def lead_rows(key: str, matrix: dict, review: dict, today: date, holding_days=_UNSET) -> list[tuple]:
    """(strategy, index) for every qualifying candidate; index None = the preset original."""
    if not review or review.get("failed_expiries") or not _finite(review.get("anchor")) or review["anchor"] <= 0:
        return []
    rows = []
    single = (matrix.get("singles") or {}).get(key)
    if (review.get("original") or {}).get("reason") is None and lead_valid(key, single, today, holding_days):
        rows.append((single, None))
    rows += [(s, i) for i, s in enumerate(review.get("alternatives") or []) if lead_valid(key, s, today, holding_days)]
    return rows


def research_lead(key: str, matrix: dict, review: dict, today: date, holding_days=_UNSET):
    """The deterministic quote-quality lead: spread, then OI, anchor distance, expiry, identity."""
    rows = lead_rows(key, matrix, review, today, holding_days)
    if not rows:
        return None
    anchor = review["anchor"]

    def order(row):
        leg = row[0]["legs"][0]
        return (leg["spread_pct"], -leg["oi"], abs(leg["strike"] - anchor), _dte(leg["expiry"], today),
                leg["option_symbol"], -1 if row[1] is None else row[1])
    return min(rows, key=order)
